"""Workload, target, and run specifications.

Three frozen specs, separated by what a fingerprint is allowed to change.
Defaults live on the dataclasses. Resolution (preset, environment, CLI)
is in :mod:`asrbench.config` and produces one :class:`ResolvedConfig`.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass, field
from types import MappingProxyType
from typing import Any

from asrbench.audio import SAMPLE_RATE
from asrbench.definitions import (
    CHECKPOINT_SOURCE_UNVERIFIED,
    DEFAULT_LOOKAHEAD_IDENTITY_POLICY,
    DEFAULT_NORMALIZATION_POLICY,
    DEFAULT_PERCENTILE_METHOD,
    DEFAULT_SUSTAINABILITY_POLICY,
    LATENCY_METRIC_TTFS,
    MODE_STREAMING,
)

#: Harvard sentence used by the mock preset. Public-domain phonetic text,
#: not a corpus transcript.
DEFAULT_REFERENCE = "the birch canoe slid on the smooth planks"


@dataclass(frozen=True)
class ClipSpec:
    """Identity of the audio offered to the server.

    ``path`` is how a file clip is found on this machine. It is not part
    of the workload fingerprint. ``digest`` covers the PCM16 payload.
    """

    id: str = "mock-silence-1.6s"
    generator: str = "pcm16-silence"
    duration_s: float | None = 1.6
    sample_rate: int = SAMPLE_RATE
    digest: str | None = None
    path: str | None = None
    licence: str = "CC0-1.0"
    attribution: str = "Synthetic silence generated by asrbench; no corpus."
    note: str = (
        "Mock path only. Not a streaming-behavior claim; clip duration "
        "is below a full encoder context."
    )


@dataclass(frozen=True)
class PopulationEntry:
    """One slice of the offered population.

    ``lookahead_ms_label`` is carried for humans. The fingerprint keeps
    the frame count and drops the label.
    """

    lanes: int
    cadence_ms: int | None
    lookahead_frames: int | None
    lookahead_ms_label: float | None = None
    #: NVIDIA right-context frame count ``r``. Hard operating-point identity.
    att_context_right: int | None = None


@dataclass(frozen=True)
class PassPolicy:
    """The conjunction thresholds. They do not change offered work.

    ``latency_metric`` is ``ttfs``, ``response_latency``,
    ``finalization``, or ``frontier_lag``. One is never substituted for
    another by a default. TTFS is secondary to finalization.
    """

    admission_fraction_min: float = 1.0
    first_partial_presence_min: float = 1.0
    latency_metric: str = LATENCY_METRIC_TTFS
    latency_percentile: float = 99.0
    latency_slo_s: float = 1.0
    sustainability_policy: str = DEFAULT_SUSTAINABILITY_POLICY
    sustainability_min: float = 1.0
    accuracy_tolerance: float = 0.0
    normalization_policy: str = DEFAULT_NORMALIZATION_POLICY


@dataclass(frozen=True)
class WorkloadSpec:
    """Everything that can change the work offered to the server."""

    clip: ClipSpec = field(default_factory=ClipSpec)
    reference_transcript: str | None = DEFAULT_REFERENCE
    mode: str = MODE_STREAMING
    pacing: bool = True
    chunk_ms: int = 160
    cadence_ms: int | None = 320
    lookahead_frames: int | None = 4
    lookahead_ms_label: float | None = 320.0
    #: NVIDIA ``att_context_size`` right context. Hard operating point.
    att_context_right: int | None = None
    lanes: int = 1
    rate_rps: float | None = None
    iterations: int = 1
    warmup: int = 0
    trials: int = 1
    timeout_s: float = 5.0
    seed: int = 0
    language: str = "en"
    punctuation: bool = False
    diarization: bool = False
    interim_results: bool = True
    #: Decoder name, such as ``greedy`` or ``beam``. Hard decode identity.
    decoder: str | None = None
    #: Language model, such as ``none`` or ``n-gram``. Hard decode identity.
    language_model: str | None = None
    #: Workload key for word latency. The adapter sends the same flag.
    enable_word_time_offsets: bool = False
    transcript_policy: str = "final-and-interims"
    population: tuple[PopulationEntry, ...] = ()
    #: When set, and the user did not pass ``--iterations``, each lane
    #: runs this many measured iterations. A trial is this value times
    #: ``lanes`` sessions, not this value times ``lanes`` squared. The
    #: resolved ``iterations`` value is what the workload fingerprint
    #: records.
    iterations_per_stream: int | None = None
    #: Published correctness grid. Recorded, not executed, and not identity.
    correctness_streams: tuple[int, ...] = ()
    #: Published performance grid. Recorded, not executed, and not identity.
    performance_streams: tuple[int, ...] = ()


def _default_transport_options() -> Mapping[str, Any]:
    """Return the mock transport options, frozen against later mutation."""
    return MappingProxyType(
        {
            "interim_every_chunks": 2,
            "transcript": DEFAULT_REFERENCE,
        }
    )


def _default_channel_options() -> Mapping[str, Any]:
    """Return empty channel tuning, frozen against later mutation.

    Keepalive and maximum message size live here, not in
    ``transport_options``. They are warn-only identity.
    """
    return MappingProxyType({})


@dataclass(frozen=True)
class TargetSpec:
    """Where the work is sent. Identity, not offered-work fingerprint.

    ``auth_env`` is the name of an environment variable. The value is
    never stored on this object. Server GPU and version fields are the
    hard hardware and software identity when present. When they are
    absent, the client probe is the fallback and is labelled as such.
    """

    endpoint_url: str = "mock://local"
    transport: str = "mock"
    model: str = "mock-asr"
    auth_env: str | None = None
    tls_verify: bool = False
    transport_options: Mapping[str, Any] = field(
        default_factory=_default_transport_options
    )
    #: Keepalive and maximum message size. Not hard identity.
    channel_options: Mapping[str, Any] = field(
        default_factory=_default_channel_options
    )
    server_version: str | None = None
    server_gpu_name: str | None = None
    server_gpu_count: int | None = None
    server_gpu_memory_mib: int | None = None
    server_driver_version: str | None = None
    #: Weights identity. Hard comparison key. Not the routing model name.
    checkpoint_id: str | None = None
    checkpoint_revision: str | None = None
    checkpoint_source: str = CHECKPOINT_SOURCE_UNVERIFIED
    #: Serving stack on the comparison axis. Not the hard key.
    engine_name: str | None = None
    engine_version: str | None = None
    #: NVIDIA precision names, joined with ``+`` when mixed. Record only.
    precision: str | None = None
    tf32: bool | None = None
    #: Warn-only concurrency knobs.
    batch_size: int | None = None
    max_num_seqs: int | None = None
    gpu_memory_utilization: float | None = None
    cuda_version: str | None = None
    torch_version: str | None = None
    #: ``loopback``, ``same-region``, or ``wan``. Warn-only.
    client_location: str | None = None

    def __post_init__(self) -> None:
        """Freeze option maps so a caller cannot mutate them later."""
        object.__setattr__(
            self,
            "transport_options",
            MappingProxyType(dict(self.transport_options)),
        )
        object.__setattr__(
            self,
            "channel_options",
            MappingProxyType(dict(self.channel_options)),
        )


@dataclass(frozen=True)
class RunSpec:
    """How the run is observed. Not part of the workload fingerprint.

    ``output_path`` is recorded and then excluded from the observation
    fingerprint: two runs that differ only by ``--out`` observed the same
    way.
    """

    output_path: str | None = None
    verbosity: int = 0
    profiler: str | None = None
    percentile_method: str = DEFAULT_PERCENTILE_METHOD
    lookahead_identity_policy: str = DEFAULT_LOOKAHEAD_IDENTITY_POLICY
    pass_policy: PassPolicy = field(default_factory=PassPolicy)
    #: Write the perf-table TSV beside the receipt. Not offered work and
    #: not part of the observation fingerprint.
    emit_tsv: bool = False


@dataclass(frozen=True)
class ReproductionOverride:
    """One field this run changed relative to the receipt it reproduced.

    Values are canonical JSON text so the record stays frozen and
    printable. The output path is not included: a reproduction is
    allowed to write a different file.
    """

    path: str
    receipt: str
    resolved: str


@dataclass(frozen=True)
class ResolvedConfig:
    """One fully resolved run. Frozen, and free of secret values.

    ``reproduction_overrides`` is stripped from the receipt's
    ``resolved_config`` and written on the receipt's ``reproduction``
    object, so two reproductions that differ only by ``--out`` still
    have equal resolved configs.
    """

    workload: WorkloadSpec = field(default_factory=WorkloadSpec)
    target: TargetSpec = field(default_factory=TargetSpec)
    run: RunSpec = field(default_factory=RunSpec)
    reproduction_overrides: tuple[ReproductionOverride, ...] = ()


def default_config() -> ResolvedConfig:
    """Return the dataclass defaults as one resolved config.

    Returns:
        A config no preset has touched. Clip digest is still unset;
        resolution fills it.
    """
    return ResolvedConfig()
