"""NVIDIA streaming-table rows from receipts run against the stand-in."""

import json
from pathlib import Path
from typing import Any

import pytest

pytest.importorskip("grpc")
pytest.importorskip("riva.client.proto.riva_asr_pb2")
pytest.importorskip("riva.client.proto.riva_asr_pb2_grpc")

from asrbench.cli import main
from asrbench.reporters import (
    NVIDIA_TABLE_COLUMNS,
    nvidia_streaming_row,
    nvidia_table_tsv,
)
from tests.riva_fake import FakeRiva, RunningFake

_PRESET = Path("presets/nim-compat-streaming.json")


def _run(
    tmp_path: Path, mode: str, *extra: str, duration_s: float = 0.32
) -> dict[str, Any]:
    payload = json.loads(_PRESET.read_text(encoding="utf-8"))
    server = RunningFake(FakeRiva(mode=mode))
    payload["workload"]["clip"] = {
        "id": "nvidia-table-fake-silence",
        "generator": "pcm16-silence",
        "duration_s": duration_s,
        "sample_rate": 16000,
        "licence": "CC0-1.0",
        "attribution": "Synthetic silence generated by asrbench; no corpus.",
        "note": "In-process stand-in. Not the LibriSpeech cell.",
    }
    payload["workload"]["timeout_s"] = 5
    payload["workload"]["interim_results"] = False
    payload["target"]["endpoint_url"] = server.endpoint
    payload["target"]["auth_env"] = None
    payload["target"]["tls_verify"] = False
    payload["target"]["transport_options"]["use_ssl"] = False
    payload["run"]["percentile_method"] = "floor_index"
    preset = tmp_path / f"{mode}.json"
    preset.write_text(json.dumps(payload), encoding="utf-8")
    out = tmp_path / f"{mode}-receipt.json"
    try:
        code = main(["run", "--preset", str(preset), "--out", str(out), *extra])
    finally:
        server.stop()
    assert code == 0
    receipt: dict[str, Any] = json.loads(out.read_text(encoding="utf-8"))
    return receipt


def test_row_is_comparable_with_one_response_per_chunk(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    receipt = _run(tmp_path, "per-chunk-final-last", "--lanes", "2")
    assert receipt["schema_version"] == "asrbench-receipt/6"
    row = nvidia_streaming_row(receipt, "r.json")
    assert row["streams"] == 2
    assert row["chunk_ms"] == 160
    assert row["compat_status"] == "measured"
    assert row["trials_measured"] == "3/3"
    assert row["comparable"] is True
    assert row["not_comparable"] == ""
    assert row["latency_source"] == "riva_compat"
    assert row["pacing_validity"] == "paced"
    assert row["interim_results"] is False
    assert row["word_time_offsets"] is False
    assert row["iterations_per_lane"] == 3
    assert row["trailing_extra_ignored"] == 0
    assert isinstance(row["p50_ms_std"], float)
    assert isinstance(row["throughput_rtfx_std"], float)
    assert isinstance(row["finalization_p50_ms"], float)
    for column in ("avg_ms", "p50_ms", "p90_ms", "p95_ms", "p99_ms"):
        assert isinstance(row[column], float) and row[column] > 0
    trials = receipt["trials"]
    expected = sum(
        trial["reduction"]["riva_client_compat_s"]["p90"] for trial in trials
    ) / len(trials)
    assert row["p90_ms"] == pytest.approx(expected * 1000)
    rtfx = sum(
        trial["reduction"]["aggregate_rtfx"]["value"] for trial in trials
    ) / len(trials)
    assert row["throughput_rtfx"] == pytest.approx(rtfx)
    assert isinstance(row["final_avg_ms"], float)

    receipt_path = tmp_path / "per-chunk-final-last-receipt.json"
    capsys.readouterr()
    assert main(["nvidia-table", str(receipt_path)]) == 0
    lines = capsys.readouterr().out.splitlines()
    assert lines[0].startswith("# One row per receipt")
    assert lines[1].split("\t") == list(NVIDIA_TABLE_COLUMNS)
    assert len(lines) == 3


def test_trailing_extra_response_still_yields_a_row(tmp_path: Path) -> None:
    receipt = _run(tmp_path, "per-chunk")
    row = nvidia_streaming_row(receipt, "r.json")
    assert row["compat_status"] == "measured"
    assert row["trailing_extra_ignored"] == 9
    assert row["latency_source"] == "riva_compat"
    assert row["comparable"] is True


def test_unpaced_row_is_not_comparable(tmp_path: Path) -> None:
    # riva_streaming_asr_client prints latency only under
    # --simulate_realtime: unpaced compat is not_applicable.
    receipt = _run(tmp_path, "per-chunk", "--no-pacing")
    row = nvidia_streaming_row(receipt, "r.json")
    assert row["compat_status"] == "not_applicable"
    assert row["pacing_validity"] == "pacing_disabled"
    assert row["comparable"] is False
    assert "pacing_validity" in row["not_comparable"].split(",")


def test_final_only_server_leaves_latency_empty(tmp_path: Path) -> None:
    receipt = _run(tmp_path, "final")
    row = nvidia_streaming_row(receipt, "r.json")
    assert row["compat_status"] == "invalid"
    assert row["latency_source"] == "n/a:final_only"
    assert row["avg_ms"] is None and row["p99_ms"] is None
    assert row["comparable"] is False
    assert "latency_source" in row["not_comparable"].split(",")
    assert isinstance(row["throughput_rtfx"], float)
    assert isinstance(row["finalization_p50_ms"], float)


def test_non_one_to_one_falls_back_to_chunk_coverage(tmp_path: Path) -> None:
    paired = nvidia_streaming_row(_run(tmp_path, "paired-interims"), "p")
    assert paired["compat_status"] == "invalid"
    assert paired["latency_source"] == "chunk_coverage/send_watermark"
    assert isinstance(paired["avg_ms"], float)
    assert paired["comparable"] is False
    assert paired["not_comparable"] == "latency_source"
    frontier = nvidia_streaming_row(
        _run(tmp_path, "cadence-frontier", duration_s=0.8), "f"
    )
    # Five chunks, two interims and a final: not 1:1.
    assert frontier["compat_status"] == "invalid"
    assert frontier["latency_source"] == "chunk_coverage/audio_processed"
    assert isinstance(frontier["p90_ms"], float)
    assert frontier["comparable"] is True


def test_comparable_needs_interims_off_and_three_iterations(
    tmp_path: Path,
) -> None:
    receipt = _run(tmp_path, "per-chunk-final-last", "--iterations", "1")
    receipt["resolved_config"]["workload"]["interim_results"] = True
    receipt["resolved_config"]["workload"]["enable_word_time_offsets"] = True
    row = nvidia_streaming_row(receipt, "r.json")
    assert row["comparable"] is False
    assert set(row["not_comparable"].split(",")) >= {
        "interim_results",
        "word_time_offsets",
        "iterations_per_lane",
    }


def test_row_is_not_comparable_without_floor_index_or_samples() -> None:
    def trial(status: str, value: float | None) -> dict[str, Any]:
        return {
            "reduction": {
                "riva_client_compat_s": {
                    "availability": status,
                    "mean": value,
                    "p50": value,
                    "p90": value,
                    "p95": value,
                    "p99": value,
                },
                "aggregate_rtfx": {"value": 1.0},
            }
        }

    receipt: dict[str, Any] = {
        "resolved_config": {
            "workload": {"mode": "streaming", "chunk_ms": 160, "lanes": 1},
            "run": {"percentile_method": "floor_index"},
        },
        "trials": [trial("measured", 0.1), trial("invalid", None)],
    }
    row = nvidia_streaming_row(receipt, "old.json")
    assert row["comparable"] is False
    assert row["trials_measured"] == "1/2"
    assert row["avg_ms"] == pytest.approx(100.0)
    assert row["compat_status"] == "invalid,measured"
    # A receipt from before the split has no split columns, not zeros.
    assert row["final_avg_ms"] is None
    receipt["trials"] = [trial("measured", 0.1)]
    receipt["resolved_config"]["run"]["percentile_method"] = "numpy_linear"
    assert nvidia_streaming_row(receipt, "x")["comparable"] is False
    text = nvidia_table_tsv([row])
    assert "\tfalse\t" in text


def test_nvidia_table_rounds_floats_to_five_significant_figures() -> None:
    row: dict[str, Any] = {name: None for name in NVIDIA_TABLE_COLUMNS}
    row["avg_ms"] = 9.423456789012345
    row["streams"] = 4
    text = nvidia_table_tsv([row])
    cells = text.splitlines()[2].split("\t")
    assert cells[NVIDIA_TABLE_COLUMNS.index("avg_ms")] == "9.4235"
    assert cells[NVIDIA_TABLE_COLUMNS.index("streams")] == "4"


def test_offline_receipt_projects_to_an_offline_row(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    receipt = _run(
        tmp_path,
        "final",
        "--mode",
        "offline",
        "--no-pacing",
        "--lanes",
        "4",
        "--iterations",
        "2",
    )
    pooled = receipt["summary"]["pooled"]
    assert pooled["counts"]["attempted"] == 24
    assert pooled["counts"]["completed"] == 24
    assert pooled["offline_rtfx"]["availability"] == "measured"
    assert pooled["offline_rtfx"]["validity"] == "offline_cell"
    assert pooled["streaming_rtfx"]["availability"] == "unavailable"
    assert pooled["finalization_s"]["n_with_measure"] == 24
    assert pooled["riva_client_compat_s"]["availability"] == "not_applicable"
    server = pooled["server_audio_rtfx"]
    assert server["availability"] == "measured"
    assert server["mismatch"] is False
    assert pooled["pacing_fidelity"]["reason"] == "mode_is_offline"
    assert pooled["word_latency_s"]["availability"] == "not_applicable"
    assert pooled["word_latency_s"]["reason"] == "mode_is_offline"
    row = nvidia_streaming_row(receipt, "offline.json")
    assert row["mode"] == "offline"
    assert row["streams"] == 4
    assert row["compat_status"] == "all_requests_completed"
    assert row["trials_measured"] == "3/3"
    assert row["comparable"] is True
    assert isinstance(row["p99_ms"], float) and row["p99_ms"] > 0
    assert isinstance(row["throughput_rtfx"], float)
    assert isinstance(row["throughput_rtfx_server"], float)
    assert abs(row["throughput_server_gap"]) < 0.005
    assert row["latency_source"] == "asrbench_only/finalization_s"
    text = nvidia_table_tsv([row])
    assert "# One row per offline receipt" in text


