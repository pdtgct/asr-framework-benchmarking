"""`asrbench sweep`: one receipt per stream count, against the stand-in."""

import json
from pathlib import Path
from typing import Any

import pytest

pytest.importorskip("grpc")
pytest.importorskip("riva.client.proto.riva_asr_pb2")
pytest.importorskip("riva.client.proto.riva_asr_pb2_grpc")

from asrbench.cli import main
from tests.riva_fake import FakeRiva, RunningFake


def _preset(tmp_path: Path, endpoint: str, streams: list[int]) -> Path:
    payload: dict[str, Any] = json.loads(
        Path("presets/nim-compat-streaming.json").read_text(encoding="utf-8")
    )
    payload["workload"]["clip"] = {
        "id": "sweep-silence",
        "generator": "pcm16-silence",
        "duration_s": 0.32,
        "sample_rate": 16000,
        "licence": "CC0-1.0",
        "attribution": "Synthetic silence generated by asrbench; no corpus.",
        "note": "In-process stand-in.",
    }
    payload["workload"]["timeout_s"] = 5
    payload["workload"]["trials"] = 2
    payload["workload"]["performance_streams"] = streams
    payload["target"]["endpoint_url"] = endpoint
    payload["target"]["auth_env"] = None
    payload["target"]["tls_verify"] = False
    payload["target"]["transport_options"]["use_ssl"] = False
    payload["run"]["percentile_method"] = "floor_index"
    preset = tmp_path / "sweep.json"
    preset.write_text(json.dumps(payload), encoding="utf-8")
    return preset


def test_sweep_runs_performance_streams(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    server = RunningFake(FakeRiva(mode="per-chunk-final-last"))
    preset = _preset(tmp_path, server.endpoint, [1, 3])
    out = tmp_path / "receipts"
    try:
        code = main(
            [
                "sweep",
                "--preset",
                str(preset),
                "--out-dir",
                str(out),
                "--no-pacing",
            ]
        )
    finally:
        server.stop()
    assert code == 0
    for lanes in (1, 3):
        receipt = json.loads(
            (out / f"c160-n{lanes}.json").read_text(encoding="utf-8")
        )
        workload = receipt["resolved_config"]["workload"]
        assert workload["lanes"] == lanes
        # iterations_per_stream (3) is per lane, as `run --lanes N` does.
        assert workload["iterations"] == 3
        assert receipt["summary"]["pooled"]["counts"]["attempted"] == (
            lanes * 3 * 2
        )
        assert (out / f"c160-n{lanes}.tsv").exists()
        assert (out / f"c160-n{lanes}.console.txt").exists()
    table = (out / "c160-nvidia-layout.tsv").read_text(encoding="utf-8")
    lines = table.splitlines()
    assert len(lines) == 4
    assert lines[2].split("\t")[:4] == [
        "c160-n1.json",
        "streaming",
        "160",
        "1",
    ]
    assert lines[3].split("\t")[3] == "3"
    assert capsys.readouterr().out == table
    # The directory holds only receipts as JSON, so `index` reads it.
    assert main(["index", str(out), "--out", str(tmp_path / "i.jsonl")]) == 0


def test_streams_flag_overrides_and_prefix(tmp_path: Path) -> None:
    server = RunningFake(FakeRiva(mode="final"))
    preset = _preset(tmp_path, server.endpoint, [1, 4, 8])
    out = tmp_path / "r"
    try:
        code = main(
            [
                "sweep",
                "--preset",
                str(preset),
                "--out-dir",
                str(out),
                "--streams",
                "2",
                "--prefix",
                "site",
                "--no-pacing",
                "--trials",
                "1",
            ]
        )
    finally:
        server.stop()
    assert code == 0
    assert sorted(path.name for path in out.glob("*.json")) == ["site-n2.json"]


def test_sweep_refuses_lanes_and_out(tmp_path: Path) -> None:
    preset = _preset(tmp_path, "127.0.0.1:1", [1])
    base = ["sweep", "--preset", str(preset), "--out-dir", str(tmp_path)]
    assert main([*base, "--lanes", "2"]) == 2
    assert main([*base, "--out", "x.json"]) == 2
    empty = _preset(tmp_path, "127.0.0.1:1", [])
    assert (
        main(["sweep", "--preset", str(empty), "--out-dir", str(tmp_path)]) == 2
    )
    with pytest.raises(SystemExit):
        main([*base, "--streams", "0"])
